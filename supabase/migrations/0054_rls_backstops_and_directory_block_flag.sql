begin;

-- -----------------------------------------------------------------------------
-- 1. `expenses` and `booking_transport` — the missing WRITE half
--
-- Both tables have had a SELECT policy since 0014 and no write policy ever. RLS
-- denies what no policy allows, so INSERT and UPDATE are currently refused on
-- both for every role including Owner.
--
-- SCOPE, STATED HONESTLY: this is a backstop landed AHEAD of the wiring, not a
-- fix for a live breakage. Neither table is queried from the app today —
-- `grep` finds no `from('expenses')` or `from('booking_transport')` anywhere in
-- `src/`, and `src/modules/reports/ExpenseReports.tsx` still reads the
-- `src/data/expenseReports.ts` fixture. So nothing is broken on screen right
-- now; what this removes is the wall those screens would hit on their first
-- real insert. Landing it now, while the tables are unused, is also the only
-- moment a write-policy change carries no regression risk.
--
-- WRITTEN AS SEPARATE `for insert` / `for update` POLICIES, NOT `for all`, and
-- that is deliberate. Permissive policies for the same command are OR'd
-- together, so a `for all` policy's USING clause would union into the existing
-- SELECT surface and silently widen who can READ these tables — on
-- `booking_transport` it would have added Manager and Accounts to 0014's
-- deliberately-enumerated read list. Splitting the commands leaves the read
-- surface of both tables exactly as 0014 left it.
--
-- DELETE is intentionally left with no policy on both tables. Law 3 — nothing is
-- deleted — and both are already in a `revoke delete` list (0006:537-552 for
-- `expenses`, 0002:416 for `booking_transport`). Absence of a DELETE policy is
-- the RLS-level restatement of that, and is the correct posture, not an
-- oversight.
-- -----------------------------------------------------------------------------

-- `expenses`: money, so the write tier is the finance tier. This matches the
-- read gate already in force (`expenses_money_blind` uses `auth_can_view_money()`,
-- and `auth_is_finance_or_admin()` is a strict subset of it), so no role gains
-- read access it did not already have.
drop policy if exists expenses_insert_finance on expenses;
create policy expenses_insert_finance on expenses
  for insert
  with check (auth_is_finance_or_admin());

drop policy if exists expenses_update_finance on expenses;
create policy expenses_update_finance on expenses
  for update
  using (auth_is_finance_or_admin())
  with check (auth_is_finance_or_admin());

-- `booking_transport`: the config tier, scoped narrower than the read tier on
-- purpose. 0014:127-131 ruled Driver READ-ONLY here ("the trip it is assigned,
-- the booking it is delivering, no money"), which settles Driver but says
-- nothing about who WRITES.
--
-- TODO(decision): whether Warehouse may write `booking_transport` at handover.
-- 0002:406 comments that `number_plate` is "captured at handover", and Warehouse
-- is the role that performs handover — so there is a real argument that Warehouse
-- needs UPDATE on at least that column. No migration or spec rules on it. It is
-- left OUT here rather than guessed, because a policy that is too narrow fails
-- closed and shows up immediately as "Warehouse cannot save the plate", whereas
-- one that is too wide hands the floor write access to `delivery_charge` and
-- `fuel_charge` and nobody notices. If the ruling comes back "yes", the fix is a
-- column-scoped UPDATE policy for Warehouse, not a widening of this one.
--
-- Note also a PRE-EXISTING Law 6 tension this migration does NOT widen and does
-- not fix: `booking_transport` carries `delivery_charge` and `fuel_charge`, and
-- 0014's read policy admits Warehouse and Driver to the table with no
-- column-level masking, despite that same section's comment saying "no money".
-- The masking pattern this schema uses elsewhere (revoke the columns, expose a
-- `_v` view — 0019, 0034:141-154, 0035, 0038, 0039) has never been applied here.
-- Flagged so it is visible; fixing it is its own reviewed change, since it moves
-- a read surface that screens already consume.
drop policy if exists booking_transport_insert_ops on booking_transport;
create policy booking_transport_insert_ops on booking_transport
  for insert
  with check (auth_is_finance_or_admin());

drop policy if exists booking_transport_update_ops on booking_transport;
create policy booking_transport_update_ops on booking_transport
  for update
  using (auth_is_finance_or_admin())
  with check (auth_is_finance_or_admin());


-- -----------------------------------------------------------------------------
-- 1b. `portal_users` / `portal_sessions` / `portal_auth_challenges`
--      — the genuine three, deliberately STILL left without policies
--
-- These three are really RLS-enabled-with-zero-policies, which is deny-all, and
-- that is the correct state today. The draft proposed replacing the implicit
-- denial with three explicit `using (false)` policies, on the reasoning that an
-- explicit deny reads as a decision while an absent policy reads as an oversight.
-- That reasoning is good and the TODO below is kept in full because of it — but
-- the policies themselves are NOT created here, because 0049 already ruled the
-- other way and gave a reason that adding them would defeat:
--
--   0049:153-155 — "They remain fail-closed in the meantime: RLS on with no
--   policy denies every row to `anon` and `authenticated`. The three INFO
--   findings therefore stay on the advisor report ON PURPOSE."
--
-- Adding `using (false)` policies changes no behaviour whatsoever (deny-all
-- either way) but DOES clear those three Supabase advisor INFO findings — which
-- is precisely the standing reminder 0049 chose to keep on the board until the
-- binding question below is answered. Silencing a deliberately-kept signal while
-- changing nothing real is a bad trade, so the prior ruling stands.
--
-- TODO(decision) — how a portal session binds to a `client_id`. Every policy in
-- this schema is written in terms of `auth_user_role()`, which resolves a
-- `system_role` from `users.primary_role` and defaults to 'Client'. Portal users
-- are by construction not staff and have no `system_role`, so there is no way to
-- write `using (...)` for them in the existing vocabulary. The candidates — a
-- `portal_user_id` GUC, a Supabase Auth JWT claim, or service-role-only with all
-- portal traffic behind an edge function — are a real unmade design decision.
-- Guessing it wrong does not fail closed: it exposes one client's bookings and
-- invoices to another client. Deny-all until it is ruled. Logged in PLAN.md §6.32
-- and §4; see also 0005:1046, which independently requires that
-- `portal_auth_challenges` be service-role only ("reading another phone's
-- challenge row is account takeover").
--
-- Consequence, stated plainly so it is not rediscovered as a bug: the Client
-- Portal cannot authenticate anyone as deployed. That is intended, and it is
-- the safe direction.
-- -----------------------------------------------------------------------------

comment on table portal_users is
  'DENY-ALL: RLS enabled, no policy, on purpose. Pending the portal session -> client_id binding decision (TODO in 0054, ruled deny-all in 0049, logged PLAN.md 6.32/4). The Client Portal cannot authenticate until that is settled and real policies replace the denial.';


-- -----------------------------------------------------------------------------
-- 2. `client_directory_v` — expose the blocked flag
--
-- `client_status` has exactly two members, Active and Deactivated. 0001:832 says
-- so and adds "Blocked is NOT a member of this enum - it is a flag on
-- client_flags (Blacklist.md)". Verified: `client_flag_type` (0001:895-899) is
-- ('VIP', 'Blocked', 'Upgrade Candidate'), and `client_flags` (0005:225-244) has
-- `client_id`, `flag_type` and `removed_at` under exactly those names.
--
-- The directory view never joined `client_flags`, so a blacklisted client renders
-- in the directory as an ordinary one and the "Blocked Balance" KPI on the
-- Clients screen counts nothing. `src/lib/queries/clients.ts:199-217` already
-- documents this gap and names this migration as the fix, so the app side is
-- waiting on exactly the column added below.
--
-- `removed_at is null` is the live-flag test. Flags append to state and are never
-- deleted (Law 3 — and `client_flags` is in 0005's `revoke delete` list), so a
-- lifted block is a removal timestamp, not a missing row. 0005:254-255:
-- "Removal is a state change on the row; the row is never deleted."
--
-- WHY THE WHOLE SELECT LIST IS RESTATED
-- -------------------------------------
-- The draft assumed 0053 built this view on top of a `client_directory_v_base`,
-- which would have made this a two-line `select d.*, exists(...)`. There is no
-- such base view — it appears nowhere in 0001–0053. 0052:31 and 0053:47 both
-- define `client_directory_v` directly over `clients_v`.
--
-- `create or replace view` replaces the view body wholesale; it cannot add a
-- column to a body it does not restate, and it will refuse outright to drop,
-- rename, retype or REORDER any existing column. So the list below is 0053:48-140
-- reproduced column-for-column in its original order — all 30 of them, ending at
-- `kyc_verified_count` — with `is_blocked` appended as the 31st and last. The
-- `where auth_is_staff()` row gate and every lateral join are carried over
-- unchanged. Nothing here is new except the final column.
-- -----------------------------------------------------------------------------
create or replace view client_directory_v as
select
  c.id,
  c.client_code,
  c.name,
  c.phone,
  c.email,
  c.address_line,
  c.city,
  c.district,
  c.country,
  c.status,
  c.client_since,
  c.type_parent,
  c.org_subtype,
  c.pan_vat,
  c.deactivated_at,
  c.created_at,
  c.approved_credit_limit,
  c.payment_terms,

  -- Money aggregates: NULL for a money-blind session, never 0. A rendered
  -- "Rs 0" would be a false claim about a real balance (Foundation §8.3).
  case when auth_can_view_money() then coalesce(inv.outstanding_total, 0) else null end
    as outstanding_amount,
  case when auth_can_view_money() then coalesce(dep.held_total, 0) else null end
    as deposit_held_amount,
  case when auth_can_view_money() then coalesce(pay.paid_total, 0) else null end
    as total_paid_amount,

  coalesce(bk.active_count, 0)  as active_bookings_count,
  coalesce(bk.total_count, 0)   as total_bookings_count,
  bk.last_pickup_at,

  ct.full_name    as contact_name,
  ct.designation  as contact_designation,
  ct.phone        as contact_phone,

  mem.level       as membership_level,

  coalesce(doc.total_count, 0)    as kyc_docs_count,
  coalesce(doc.verified_count, 0) as kyc_verified_count,

  -- NEW IN 0054 — the only addition to 0053's projection, appended last so the
  -- replace is column-order-compatible. Not gated on auth_can_view_money():
  -- a block is an operational fact, not a monetary one, and the whole view is
  -- already behind `where auth_is_staff()`.
  exists (
    select 1
    from client_flags f
    where f.client_id = c.id
      and f.flag_type = 'Blocked'
      and f.removed_at is null
  ) as is_blocked
from clients_v c
left join lateral (
  select sum(i.outstanding_amount) as outstanding_total
  from invoices i
  where i.client_id = c.id
) inv on true
left join lateral (
  -- Held = received minus refunded minus applied. Law 5: a deposit is a
  -- liability and is deliberately NOT netted against anything owed.
  select sum(greatest(s.received_amount - s.refunded_amount - s.applied_amount, 0)) as held_total
  from security_deposits s
  where s.client_id = c.id
) dep on true
left join lateral (
  select sum(p.amount) as paid_total
  from payments p
  where p.client_id = c.id and p.status = 'Received'
) pay on true
left join lateral (
  -- There is no 'Cancelled' booking_stage: the canonical six are Quote/Booked/
  -- Packed/On Rent/Returned/Closed, and cancelling is a named terminal action
  -- recorded in `cancelled_at` (Law 3), not a stage.
  select
    count(*) filter (where b.stage <> 'Closed' and b.cancelled_at is null) as active_count,
    count(*)                                                              as total_count,
    max(b.pickup_at)                                                      as last_pickup_at
  from bookings b
  where b.client_id = c.id
) bk on true
left join lateral (
  select k.full_name, k.designation, k.phone
  from client_contacts k
  where k.client_id = c.id and k.deactivated_at is null
  order by k.is_primary desc, k.created_at
  limit 1
) ct on true
left join lateral (
  select p.level
  from client_memberships m
  join membership_plans p on p.id = m.plan_id
  where m.client_id = c.id and m.superseded_at is null
  order by m.join_date desc
  limit 1
) mem on true
left join lateral (
  select
    count(*)                                        as total_count,
    count(*) filter (where d.status = 'Verified')   as verified_count
  from client_documents d
  where d.client_id = c.id and d.archived_at is null
) doc on true
where auth_is_staff();

grant select on client_directory_v to authenticated;

comment on view client_directory_v is
  'One row per client with everything a directory row needs: aggregates (outstanding, deposit held, total paid, booking counts, last pickup), primary contact, current membership level, KYC counts, and whether the client is blocked. Query this for any client list — never re-aggregate in a screen (Law 1/Law 2). Money columns are NULL for money-blind roles, never 0. `is_blocked` is derived from client_flags, not from clients.status — Blocked is not a client_status member (0001:832).';


-- -----------------------------------------------------------------------------
-- Post-conditions. Same shape as 0049's tail check: assert the things this file
-- claims to have done, so a partial apply fails loudly instead of leaving the
-- schema in a state the comments above misdescribe.
-- -----------------------------------------------------------------------------
do $$
declare
  n int;
begin
  -- The four write policies added above, plus the two SELECT policies 0014
  -- already created dynamically = 6 across the two tables.
  select count(*) into n
    from pg_policies
   where schemaname = 'public'
     and tablename in ('expenses', 'booking_transport');

  if n <> 6 then
    raise exception '0054 post-condition failed: expected 6 policies across expenses + booking_transport, found %', n;
  end if;

  -- The portal trio must still have none — if this ever trips, someone added a
  -- policy without settling the binding decision above.
  select count(*) into n
    from pg_policies
   where schemaname = 'public'
     and tablename in ('portal_users', 'portal_sessions', 'portal_auth_challenges');

  if n <> 0 then
    raise exception '0054 post-condition failed: portal trio must remain deny-all, found % policies', n;
  end if;

  -- The view actually gained the column, and gained it last.
  select count(*) into n
    from information_schema.columns
   where table_schema = 'public'
     and table_name = 'client_directory_v'
     and column_name = 'is_blocked';

  if n <> 1 then
    raise exception '0054 post-condition failed: client_directory_v.is_blocked missing';
  end if;

  raise notice '0054 OK — 4 write policies added, portal trio still deny-all, client_directory_v.is_blocked present';
end $$;

commit;


