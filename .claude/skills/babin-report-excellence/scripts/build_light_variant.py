#!/usr/bin/env python3
"""Emit the light (export) token block so it can't drift from the dark set.

The dark surfaces/text invert to a light scale; the two brand accents are
darkened until they clear WCAG AA (4.5:1) on white, so labels/icons on the
export stay readable. Prints a :root/.export CSS block to stdout.

Run: python build_light_variant.py  >  ../assets/_light-tokens.css
"""

def _lin(c):
    c /= 255.0
    return c/12.92 if c <= 0.03928 else ((c+0.055)/1.055)**2.4

def lum(h):
    h = h.lstrip("#"); r,g,b = (int(h[i:i+2],16) for i in (0,2,4))
    return 0.2126*_lin(r)+0.7152*_lin(g)+0.0722*_lin(b)

def ratio_on_white(h):
    return (1.0+0.05)/(lum(h)+0.05)

def darken(hexstr, target=4.5, white=True):
    """Scale RGB down until contrast on white >= target."""
    h = hexstr.lstrip("#"); r,g,b = (int(h[i:i+2],16) for i in (0,2,4))
    for _ in range(100):
        cur = ratio_on_white("#%02x%02x%02x" % (r,g,b))
        if cur >= target:
            break
        r,g,b = int(r*0.94), int(g*0.94), int(b*0.94)
    return "#%02X%02X%02X" % (r,g,b)

# fixed light surfaces/text (near-black, not #000)
LIGHT = {
    "--surface-base":   "#FFFFFF",
    "--surface-sunken": "#F4F6F9",
    "--surface-card":   "#FFFFFF",
    "--surface-raised": "#FAFBFC",
    "--surface-inset":  "#F0F3F7",
    "--border-subtle":  "#E3E8EF",
    "--border-strong":  "#C7D0DB",
    "--text-primary":   "#12202E",
    "--text-secondary": "#3A4A5C",
    "--text-muted":     "#6B7889",
}

def main():
    accent = darken("#2F7DFF")       # blue -> passes AA on white
    brand  = darken("#D9A83C")       # gold -> passes AA on white
    LIGHT["--accent"] = accent
    LIGHT["--accent-brand"] = brand
    print("/* AUTO-GENERATED by build_light_variant.py — do not hand-edit */")
    print(".export, @media print { :root {")
    for k, v in LIGHT.items():
        print(f"  {k}: {v};")
    print("} }")
    # report the accent ratios as a comment for auditing
    print(f"/* accent {accent} = {ratio_on_white(accent):.2f}:1 on white; "
          f"brand {brand} = {ratio_on_white(brand):.2f}:1 on white */")

if __name__ == "__main__":
    main()
