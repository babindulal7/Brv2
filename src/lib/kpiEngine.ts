import type { RentalRow } from '../data/rentals'
import { rupees, Paisa } from './money'

/**
 * KPI Engine — Centralizes all KPI calculations.
 * Fixes the P2 issue where "Payment Due" and "Revenue Today" displayed
 * conflicting hardcoded values across the Dashboard and Rentals list.
 */

export function calculatePaymentDue(rows: RentalRow[]): Paisa {
  // Sum unpaid invoiced balances across all open bookings.
  // We use `due` field on the rows.
  return rupees(
    rows.reduce((sum, r) => {
      // Only sum balances for active bookings (not cancelled)
      if (r.flags.includes('Cancelled')) return sum
      return sum + (r.due ? r.due / 100 : 0) // Divide by 100 to convert paisa to rupees temporarily, then convert back
    }, 0)
  )
}

export function calculateRevenueToday(rows: RentalRow[], today: Date): Paisa {
  // Revenue generated by bookings starting today.
  // We identify "today" bookings by matching `pickup.ad` to `today`.
  const todayKey = today.toISOString().split('T')[0]
  
  return rupees(
    rows.reduce((sum, r) => {
      if (r.flags.includes('Cancelled')) return sum
      
      const pickupKey = r.pickup.ad.toISOString().split('T')[0]
      if (pickupKey === todayKey) {
        return sum + (r.amount ? r.amount / 100 : 0)
      }
      return sum
    }, 0)
  )
}

export function calculateActiveRentals(rows: RentalRow[]): number {
  return rows.filter((r) => r.status !== 'Closed' && !r.flags.includes('Cancelled')).length
}

export function countOverdue(rows: RentalRow[]): number {
  return rows.filter((r) => r.flags.includes('Overdue')).length
}

export function calculatePickupsToday(rows: RentalRow[], today: Date): { total: number; done: number } {
  const todayKey = today.toISOString().split('T')[0]
  const todayPickups = rows.filter((r) => r.pickup.ad.toISOString().split('T')[0] === todayKey)
  
  const done = todayPickups.filter((r) => r.progress > 0 && r.status !== 'Booked' && !r.flags.includes('Cancelled')).length
  return { total: todayPickups.length, done }
}

export function calculateReturnsToday(rows: RentalRow[], today: Date): { total: number; overdue: number } {
  const todayKey = today.toISOString().split('T')[0]
  const todayReturns = rows.filter((r) => r.ret.ad.toISOString().split('T')[0] === todayKey)
  
  const overdue = todayReturns.filter((r) => r.flags.includes('Overdue')).length
  return { total: todayReturns.length, overdue }
}
