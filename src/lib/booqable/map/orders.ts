/**
 * Booqable `orders` (+ `order_lines`, resolved via the same composed
 * response — see Law 2 note below) → local `bookings` + `booking_lines`
 * mapper, plus the `booking_stage_transitions` rows needed to move
 * `bookings.stage` forward.
 *
 * ## Law 1
 *
 * This file only maps. It never talks to Supabase and never talks to the
 * Booqable proxy — `sync.ts` (not written in this pass) is the only caller,
 * and it owns every DB read (existing rows, existing `external_refs`) and
 * every DB write (`idempotentInsert` / `safeUpdate` from `dataAccess.ts`). A
 * screen must never import this file directly.
 *
 * ## Law 17 — "client" only
 *
 * Per PLAN.md §0 law 17, Booqable's raw wire-format naming is allowed as an
 * identifier in exactly one file: `../types.ts`. The order's client
 * reference lives on a wire field this file cannot rename, but this file
 * never spells that raw field name itself — it goes through `../types.ts`'s
 * `getOrderClientRefId()` boundary accessor instead. Every identifier,
 * variable, comment and exported name in THIS file says "client" —
 * `clientRefs`, `client_id`, `getOrderClientRefId` — never the raw term.
 *
 * ## Law 2 — one composed object per booking, and why this file's shape
 * deviates from the plain `pull(entity, rawRecords)` default
 *
 * `client.ts`'s `flattenResource()` (used by `parseListResponse`) spreads
 * only `id` + `type` + `attributes` — it deliberately does not carry
 * `relationships` onto the flat record, so a mapper cannot walk
 * `order.relationships.order_lines` the way `resolveRelatedMany` expects.
 * That is not a gap this file needs to patch in `client.ts`: every
 * `BooqableOrderLineAttributes` already carries its own `order_id`
 * (`types.ts` §2) — the grouping key is on the child, not just the parent
 * relationship. `sync.ts` is expected to issue exactly ONE Booqable request
 * (`GET /orders?include=order_lines`), take the `included` array `client.ts`
 * already parses out, filter it to `type === 'order_lines'`, flatten each
 * entry with `flattenResource`, and pass BOTH flat arrays — `orders` and
 * `order_lines` — into `mapOrders` below. That satisfies Law 2 ("never a
 * second API call") without requiring `client.ts` to change shape. This is
 * the same reasoning `stock.ts`'s file header gives for why its exported
 * shape isn't the bare `pull(entity, rawRecords)` default either — the brief
 * calls that shape "a reasonable default if nothing more specific is
 * implied," and grouped order lines are exactly the "something more
 * specific" case.
 *
 * ## What this file does NOT own
 *
 * - **`booking_discounts`** — out of scope. This brief is "orders plus order
 *   lines plus fulfillments into bookings plus booking_lines," not
 *   `booking_discounts`. `order.discount_percentage` (a booking-LEVEL,
 *   reason/approver-gated percentage in this schema — `0002_bookings.sql`'s
 *   `booking_discounts` table, CHECK-enforced 25% hard cap and >10%
 *   reason+approver) has nowhere to land here: this file never creates a
 *   `booking_discounts` row, never reads `order.discount_percentage` at all.
 *   A future `booking_discounts` mapper must itself implement spec §7/Law 10
 *   ("inbound Booqable discounts that violate it get logged as a conflict,
 *   not blocked — they already happened"); this file only carries
 *   `order.discount_in_cents` / `order_line.discount_in_cents` through as
 *   plain per-line `booking_lines.discount_amount` (an un-gated rupee
 *   amount on that table, not a reason/approver-gated percentage), so
 *   nothing here can violate a law it never touches.
 * - **Deposits (Law 5)** — CONFIRMED 10 Aug 2026 (fact 4, `types.ts`): the
 *   order now carries a full documented deposit block — `deposit_type`,
 *   `deposit_value`, and six readonly `deposit_*_in_cents` tracking fields
 *   (target / paid / to_be_paid / held / refunded / to_refund) — and the
 *   docs confirm order totals EXCLUDE deposit except `total_in_cents`.
 *   This file still does NOT wire any of them into money flows:
 *   `map/payments.ts` owns the Law 5 classifier (deposit is a per-payment
 *   monetary dimension there), and the order-level fields are aggregates of
 *   the same money — mapping them here too would double-count the ledger.
 *   This file NEVER writes `bookings.deposit_required` and NEVER writes a
 *   deposit-shaped order line into `booking_lines` — the documented line
 *   kind is `deposit_charge` ("generated by a deposit hold action",
 *   https://developers.booqable.com/#lines) — see `isDepositLine` below.
 *   Such a line is filtered out and reported via `conflicts` (never
 *   silently dropped — spec §7 rule 2), never inserted as a priced line and
 *   never landed on `payments` (which this file cannot reach anyway).
 * - **`booking_crew_lines` / `booking_transport`** — no Booqable order
 *   field maps to either; not touched.
 * - **Push (OS → Booqable)** — spec §5.1 "OS MAY write (create plus status
 *   only)" describes the outbound direction. This is a PULL mapper only,
 *   same shape as every sibling in this directory. Nothing here calls
 *   `booqableWrite`/`booqableDelete`.
 *
 * ## Status map (spec §9) — CONFIRMED 10 Aug 2026, UNCONFIRMED_BOOQABLE_FACTS[1]
 *
 * The source enum is now documented (types.ts fact 1 entry;
 * https://developers.booqable.com/#orders-statuses): new | draft | reserved
 * | started | stopped | archived | canceled — "draft" replaced the assumed
 * "concept" (v1 APIs/webhooks still say concept), and "canceled" was
 * missing entirely.
 *
 * ```
 * new / draft -> Quote      (draft "Does not influence availability")
 * concept     -> Quote      (v1 alias of draft — see the alias note below)
 * reserved    -> Booked     (via Booqable's OrderStatusTransition/
 *                             OrderFulfillment — this file only reads the
 *                             resulting status, it does not reproduce it)
 * started     -> On Rent    (pushed at HANDOVER on Booqable's side, not at
 *                             packing — only relevant to the push direction
 *                             this file doesn't implement)
 * stopped     -> Returned
 * archived    -> Closed     (Law 3 — the row survives; `bookings` has no
 *                             `deleted_at` column, and Closed already IS
 *                             this table's Law-3-compliant terminal state)
 * canceled    -> last known stage, UNCHANGED, + the three cancellation
 *                             columns. Cancellation is a SEPARATE DIMENSION
 *                             from the six-value stage — see the next
 *                             section. Never Closed: canceled frees
 *                             inventory and blocks further booking
 *                             ("The order is canceled. Items will be
 *                             available for other rentals"), which is not
 *                             what Closed means.
 * ```
 *
 * ### v1 status aliases — fact 1's naming hazard
 *
 * Fact 1 (`types.ts`) is explicit that `draft` "used to be named concept" and
 * that **v1 APIs and v1 webhooks still return `concept`**. This bridge reads
 * v4 lists but the webhook path is v1-shaped in places (fact 3: v1 webhooks
 * use `object` instead of `resource_type` and arrive urlencoded), so a
 * `concept` can reach this mapper on a real payload. `normalizeOrderStatus`
 * below folds `concept` onto `draft` BEFORE anything else looks at the value,
 * so both spellings map identically to `Quote` and neither can fall through
 * to the unrecognised-status conflict branch.
 *
 * ## Cancellation is a dimension, not a stage (Law 3)
 *
 * `bookings` carries `cancelled_at` / `cancelled_by` / `cancellation_reason`
 * (`0002_bookings.sql`) orthogonally to `stage`, and
 * `0015_canonical_six_stages.sql` §3 is the ruling that makes this the only
 * available shape: it retired the thirteen-value `booking_stage`, removed the
 * `Cancelled` member, dropped
 * `booking_stage_transitions_cancel_needs_reason` outright ("to_stage can no
 * longer BE 'Cancelled' — the literal does not exist in the new type") and
 * REWROTE the booking constraint off `stage` and onto the timestamp:
 *
 * ```sql
 * constraint bookings_cancelled_requires_actor_and_reason check (
 *   cancelled_at is null
 *   or (cancelled_by is not null
 *       and cancellation_reason is not null
 *       and char_length(btrim(cancellation_reason)) > 0)
 * )
 * ```
 *
 * (`0002_bookings.sql`'s copy of that constraint is the PRE-0015 version,
 * still keyed on `stage <> 'Cancelled'`; 0015 line 162 is the live text and
 * the one this file codes against.) Three consequences this file obeys:
 *
 * 1. **The three columns travel together or not at all.** A canceled order
 *    with no resolvable actor must NOT be inserted/updated at all — a partial
 *    write is a CHECK violation, not a degraded import. It holds as a
 *    conflict instead.
 * 2. **The stage does not move.** `workflow.ts` §1.3, quoted by 0015's own
 *    header: "Cancelled is a flag, not a status. It preserves where the
 *    booking died." So a canceled Booqable order keeps the local booking's
 *    last known stage and emits ZERO stage transitions.
 * 3. **Nothing is un-cancelled.** No documented Booqable transition leaves
 *    `canceled`, and Law 3 has no "un-cancel" named action, so this file only
 *    ever WRITES the three columns — it never emits a null to clear them.
 *
 * This is structurally the same move spec §9 already makes for "Booqable
 * delete/archive → `deleted_at` locally": a Booqable lifecycle fact that has
 * no home in the local status enum lands on its own dedicated column.
 *
 * `Packed` has NO Booqable equivalent — "OS-only, never pushed, packing
 * never touches Booqable" (brief, verbatim). This is not just a mapping
 * absence; it creates a real forward-only-trigger problem handled by
 * `planStageAdvance` below — see that function's own comment.
 *
 * Mixed states: docs confirm the singular `status` is a SIMPLIFICATION — an
 * order can be partially started/stopped, with the full picture in the
 * readonly `statuses`/`status_counts` attributes (`types.ts` §1).
 * TODO(decision): this mapper still keys off the simplified `status`;
 * whether a mixed state should map to the further-along or further-behind
 * local stage is an unmade product decision, not guessed here.
 *
 * Archived (Law 3 / fact 6, PARTIALLY CONFIRMED 10 Aug 2026): archiving is
 * v4's only delete — orders have NO DELETE endpoint at all ("archived" is a
 * status reached via OrderStatusTransition, stopped→archived), and the only
 * documented visibility effect is "The order won't show up in default
 * search results." Orders carry NO archived/archived_at attributes — an
 * archived order is detected via `status === 'archived'` only, and sync can
 * explicitly include archived orders in lists via filter[status]. Whether
 * GET by id still returns an archived order is implied by the docs but not
 * stated — still open, see UNCONFIRMED_BOOQABLE_FACTS[6].
 *
 * ## `booking_stage` IS the canonical six, confirmed against the migrations
 *
 * `0001_enums.sql`'s original 13-value `booking_stage` was retired by
 * `0015_canonical_six_stages.sql` — the type now has exactly
 * `Quote/Booked/Packed/On Rent/Returned/Closed`, in that declared (ordinal)
 * order, matching `workflow.ts`'s `BookingStatus` string-for-string. So this
 * file maps straight onto `BookingStatus` with no intermediate translation
 * table, per the brief's own instruction not to touch the retired enum.
 *
 * `0021_forward_only_stage_transitions.sql` is the reason this file cannot
 * just `safeUpdate('bookings', id, { stage: target })`: `bookings.stage` is
 * revoked from direct UPDATE for `authenticated` and is written ONLY by
 * `apply_booking_stage_transition()`, fired by an INSERT into
 * `booking_stage_transitions`. That trigger also enforces "no skipping" (the
 * `next_booking_stage()` successor map) and "no going backward without
 * `is_reversal` + an approver" — both of which this file respects rather
 * than works around. This mapper NEVER sets `is_reversal: true` — Law 21's
 * own comment is explicit that a reversal is "a Manager-approved, audited
 * exception," and an unattended sync pass has no Manager in the loop to
 * approve one. A Booqable status that would require moving `stage` backward
 * is logged to `sync_conflicts` and left alone (see `planStageAdvance`).
 *
 * ## Law 15 — days mandatory, explicit, minimum 1
 *
 * `booking_lines.days` is `not null default 1` with `check (days >= 1)`.
 * Duration is computed from the line's own `planned_starts_at`/
 * `planned_stops_at` when present, falling back to the parent order's
 * `starts_at`/`stops_at` (the "fulfillment" dates named in the brief —
 * Booqable's wire shape has no separate "fulfillment" resource; `types.ts`
 * models planning/reservation data on `plannings`, which spec §5.1 says
 * syncs "indirectly via order writes only," i.e. never pulled as its own
 * entity by this file). `computeLineDays` below rounds to the nearest whole
 * day and floors at 1 — a computed 0 (or a negative/missing pair) imports as
 * 1 with a logged `sync_conflicts` row, per the brief, never a thrown error
 * and never a silent 0.
 *
 * ## Money
 *
 * `price_in_cents` / `discount_in_cents` / `total_in_cents` map 1:1 into
 * `Paisa` — multiply nothing (Law 8 / spec §8.2). `booking_lines.rate` /
 * `.discount_amount` are `numeric(14,2)` DECIMAL rupee columns in the real
 * DDL (same convention `products.ts` already documents for
 * `products.daily_rate`), so `toRupees()` is used at this DB-write boundary
 * — arithmetic-only, not a display read. TODO(decision) — same gap
 * `products.ts` already flags: neither `BooqableOrderAttributes` nor
 * `BooqableOrderLineAttributes` carries a currency field at all (`types.ts`
 * §1/§2), so the spec §8.2 "assert currency equals NPR, skip and log a
 * non-NPR record" rule cannot be implemented per-record here — there is
 * nothing to assert against. Left as a named gap, not a fabricated
 * always-true check.
 *
 * ## Required-but-unmappable local columns
 *
 * `bookings.branch_id` and `.delivery_type` are both `NOT NULL` with no
 * confirmed Booqable-side source:
 *   - `branch_id` — Booqable's `start_location_id` (CONFIRMED: orders carry
 *     start/stop location pairs, no single `location_id` — `types.ts` §1)
 *     is the closest candidate, but
 *     spec §5.1 places `locations` in "a settings mirror, no OS write" and
 *     never states the location->branch resolution rule (identical gap
 *     `stock.ts`'s `resolveLocation` already documents for
 *     `product_units.branch_id`/`.warehouse_id`). `OrderSyncContext.resolveBranch`
 *     below is a caller-supplied resolver, exactly mirroring `stock.ts`'s
 *     pattern; an order whose location cannot be resolved is skipped and
 *     reported via `conflicts`, never inserted with a guessed branch.
 *   - `delivery_type` — no Booqable order field distinguishes pickup /
 *     delivery / courier / third-party at all. `OrderSyncContext.defaultDeliveryType`
 *     is a caller-supplied constant (e.g. from Settings), never invented
 *     inside this file.
 * `contact_id` / `authorized_contact_id` / `project` / `pickup_location` /
 * `return_location` / `quote_expires_at` all have no Booqable source field
 * either and are simply never populated by this mapper (all nullable
 * columns — nothing to violate by omission).
 *
 * ## `booking_no` — minted, never taken from Booqable
 *
 * Same shape of gap `clients.ts` documents for `client_code`:
 * `bookings.booking_no` is `NOT NULL UNIQUE`, format-locked to
 * `^BK-[0-9]{4}-[0-9]{4}$` (AD year), immutable after creation
 * (`0002_bookings.sql`'s own column comment), and normally minted via
 * `next_document_number('BK')` (`0007_admin_security.sql` confirms a `BK`
 * prefix is registered). This file never invents one — `sync.ts` mints one
 * per NEW order via `next_document_number('BK')` and supplies it through
 * `OrderSyncContext.mintedBookingNumbers`, exactly mirroring
 * `ClientSyncContext.mintedClientCodes`. A new order with no minted number
 * available is logged as a conflict and skipped, never inserted with a
 * guessed number.
 *
 * ## `created_by` / `updated_by` / stage-transition `actor_id` — the sync actor
 *
 * All three are `NOT NULL` FKs to `users`, and this sync has no human in the
 * loop. Same reasoning `stock.ts`'s `systemActorUserId` already gives: no
 * "system sync actor" user convention exists elsewhere in this codebase, so
 * `OrderSyncContext.systemActorUserId` / `.systemActorRole` are caller-supplied,
 * never invented here. Unlike `stock.ts` (where a missing actor only blocks
 * the archive branch), `bookings.created_by` is required on EVERY insert, so
 * a sync run with no actor configured cannot insert any new booking at all —
 * every such record is skipped and reported, never inserted with a guessed
 * user id.
 *
 * ## `client_uuid` — never generated here
 *
 * Every user-written row in this schema carries `client_uuid` (Law 9), but
 * per `dataAccess.ts`'s own contract, `idempotentInsert` injects a fresh one
 * automatically when the caller's payload omits it
 * (`payload.client_uuid || generateClientUuid()`). Exactly like `stock.ts`'s
 * `ProductUnitInsert`, none of this file's insert shapes carry a
 * `client_uuid` field — that stays `sync.ts`/`dataAccess.ts`'s job, not this
 * pure mapper's.
 */

