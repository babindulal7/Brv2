import type { NavigateFunction } from 'react-router-dom'
import Icon from '../../../components/ui/Icon'
import { Button } from '../../../components/ui/Button'
import { ConfirmDialog, Modal } from '../../../components/ui'
import { ClientQuickView } from './ClientQuickView'
import { ClientHistoryDrawer } from './ClientHistoryDrawer'
import { AddClientModal } from './AddClientModal'
import { DraftEmailModal } from './DraftEmailModal'
import type { ClientRecord } from '../../../lib/queries/clients'

export interface BookingModalsProps {
  client: ClientRecord | undefined
  quickViewOpen: boolean
  setQuickViewOpen: (fn: (o: boolean) => boolean) => void
  historyOpen: boolean
  setHistoryOpen: (open: boolean) => void
  canClientBalance: boolean
  navigate: NavigateFunction
  addClientOpen: boolean
  closeAddClient: () => void
  onClientCreated: (c: ClientRecord) => void
  clientPool: readonly ClientRecord[]
  onUseExistingClient: (c: ClientRecord) => void
  emailDraftDoc: string | null
  setEmailDraftDoc: (doc: string | null) => void
  cancelIntent: 'discard' | 'cancel' | null
  setCancelIntent: (intent: 'discard' | 'cancel' | null) => void
  discardDraft: () => void
  cancelDraftBooking: (reason?: string) => void | Promise<void>
  exitPrompt: 'unsaved-new' | 'unsaved-edits' | null
  setExitPrompt: (prompt: 'unsaved-new' | 'unsaved-edits' | null) => void
  doExit: () => void
  reloadPrompt: boolean
  setReloadPrompt: (prompt: boolean) => void
  onReloadQuote: () => void
  confirmedSuccess: { bookingId?: string; bookingNo: string } | null
  setConfirmedSuccess: (val: { bookingId: string; bookingNo: string } | null) => void
}

/**
 * Consolidated booking workflow modals and dialogs (Item 13 decomposition).
 *
 * Encapsulates the Client Quick View, Client History Drawer, Add Client dialog,
 * Email Draft composer, discard/cancellation confirm dialogs, and the
 * booking confirmation success dialog.
 */
export function BookingModals({
  client,
  quickViewOpen,
  setQuickViewOpen,
  historyOpen,
  setHistoryOpen,
  canClientBalance,
  navigate,
  addClientOpen,
  closeAddClient,
  onClientCreated,
  clientPool,
  onUseExistingClient,
  emailDraftDoc,
  setEmailDraftDoc,
  cancelIntent,
  setCancelIntent,
  discardDraft,
  cancelDraftBooking,
  exitPrompt,
  setExitPrompt,
  doExit,
  reloadPrompt,
  setReloadPrompt,
  onReloadQuote,
  confirmedSuccess,
  setConfirmedSuccess,
}: BookingModalsProps) {
  return (
    <>
      {client && (
        <ClientQuickView
          id="new-rental-client-quick-view"
          client={client}
          open={quickViewOpen}
          onClose={() => setQuickViewOpen(() => false)}
          onViewClient={(c) => navigate(`/clients/${c.id}`)}
          showMoney={canClientBalance}
        />
      )}

      {client && (
        <ClientHistoryDrawer
          id="new-rental-client-history"
          client={client}
          open={historyOpen}
          onClose={() => setHistoryOpen(false)}
          onOpenBooking={(bookingNo) => navigate(`/rentals/${bookingNo}`)}
          onViewClient={(c) => navigate(`/clients/${c.id}`)}
          showMoney={canClientBalance}
        />
      )}

      <AddClientModal
        isOpen={addClientOpen}
        onClose={closeAddClient}
        onCreated={onClientCreated}
        clients={clientPool}
        onUseExisting={onUseExistingClient}
      />

      <DraftEmailModal
        isOpen={emailDraftDoc !== null}
        onClose={() => setEmailDraftDoc(null)}
        documentName={emailDraftDoc ?? ''}
        toEmail={client?.email ?? ''}
        subject={`${emailDraftDoc ?? 'Document'} — ${client?.name ?? 'New Rental'}`}
        body={
          `Dear ${client?.name ?? 'Client'},\n\n` +
          `This is about the ${emailDraftDoc ?? 'document'} for your booking with Babin Rentals.\n\n` +
          `[Nothing is attached to this draft — ${emailDraftDoc ?? 'document'} documents are not generated by this system yet. ` +
          `Write the details in below, or attach your own copy, and delete this note.]\n\n` +
          `Regards,\nBabin Rentals`
        }
      />

      <ConfirmDialog
        isOpen={cancelIntent === 'discard'}
        onClose={() => setCancelIntent(null)}
        onConfirm={discardDraft}
        title="Discard this booking?"
        description="Nothing has been saved yet, so there is no draft to cancel — leaving simply discards what is on screen. The client, dates, equipment and crew entered here will be lost."
        confirmLabel="Discard and leave"
        cancelLabel="Keep editing"
        variant="danger"
      />

      <ConfirmDialog
        isOpen={cancelIntent === 'cancel'}
        onClose={() => setCancelIntent(null)}
        onConfirm={cancelDraftBooking}
        title="Cancel this draft booking?"
        description="The draft has been saved, so it is not discarded — it is moved to Cancelled and stays on the record with the reason below. Nothing is deleted."
        confirmLabel="Cancel booking"
        cancelLabel="Keep the draft"
        variant="danger"
        requireReason={{ minLength: 10, label: 'Why is this booking being cancelled?' }}
      />

      <ConfirmDialog
        isOpen={exitPrompt === 'unsaved-new'}
        onClose={() => setExitPrompt(null)}
        onConfirm={() => {
          setExitPrompt(null)
          doExit()
        }}
        title="Discard this booking?"
        description="Nothing has been saved yet. Leaving will discard what is on screen."
        confirmLabel="Discard and leave"
        cancelLabel="Keep editing"
        variant="danger"
      />

      <ConfirmDialog
        isOpen={exitPrompt === 'unsaved-edits'}
        onClose={() => setExitPrompt(null)}
        onConfirm={() => {
          setExitPrompt(null)
          doExit()
        }}
        title="Unsaved changes on draft"
        description="You have unsaved changes on this draft. Would you like to leave without saving? Your last saved draft version will remain intact."
        confirmLabel="Leave without saving"
        cancelLabel="Stay here"
        variant="default"
      />

      <ConfirmDialog
        isOpen={reloadPrompt}
        onClose={() => setReloadPrompt(false)}
        onConfirm={() => {
          setReloadPrompt(false)
          onReloadQuote()
        }}
        title="Discard edits and reload booking?"
        description="Any unsaved edits on this booking will be discarded and the latest version from the database will be loaded."
        confirmLabel="Reload booking"
        cancelLabel="Keep edits"
        variant="danger"
      />

      {confirmedSuccess && (
        <Modal
          isOpen={Boolean(confirmedSuccess)}
          onClose={() => setConfirmedSuccess(null)}
          title="Booking Confirmed!"
          size="md"
        >
          <div style={{ textAlign: 'center', padding: '16px 8px' }}>
            <div
              style={{
                display: 'inline-flex',
                alignItems: 'center',
                justifyContent: 'center',
                width: 56,
                height: 56,
                borderRadius: '50%',
                background: 'var(--st-success-bg, #ecfdf5)',
                color: 'var(--st-success-fg, #065f46)',
                marginBottom: 16,
              }}
            >
              <Icon name="check" size={28} />
            </div>
            <h3 style={{ margin: '0 0 8px', fontSize: '18px', fontWeight: 700 }}>
              Rental {confirmedSuccess.bookingNo} Confirmed
            </h3>
            <p style={{ margin: '0 0 20px', color: 'var(--text2)', fontSize: 'var(--t-body)', lineHeight: 1.5 }}>
              The booking has been successfully recorded in the database and inventory has been reserved.
            </p>
            <div style={{ display: 'flex', flexDirection: 'column', gap: 10, maxWidth: 320, margin: '0 auto' }}>
              <Button
                variant="primary"
                onClick={() => navigate(`/rentals/${confirmedSuccess.bookingNo}`)}
              >
                Open Rental Detail
              </Button>
              <Button
                variant="secondary"
                onClick={() => navigate(`/rentals/${confirmedSuccess.bookingNo}/packing`)}
              >
                Start Packing
              </Button>
              <Button
                variant="ghost"
                onClick={() => navigate('/rentals')}
              >
                Back to Rentals List
              </Button>
            </div>
          </div>
        </Modal>
      )}
    </>
  )
}
