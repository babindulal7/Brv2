#!/usr/bin/env node
/**
 * The time defaults the mock store fills on INSERT, read from the schema itself.
 *
 * Postgres fills a `default now()` or `default current_date` column when an
 * insert leaves it out, and the app relies on that: `recordPayment` omits
 * `payments.payment_date` on purpose (0006:187). The mock store only knows to do
 * the same because `src/lib/__mocks__/columnDefaults.ts` lists the columns. When
 * it did not, every payment recorded in mock mode rendered as 1/1/1970.
 *
 * This builds the migration chain in PGlite (as `check-pglite.mjs` does) and
 * lists every `public` base-table column whose default is exactly `now()` or
 * `CURRENT_DATE`. Any other time-based default is printed, not mapped.
 *
 *   node scripts/dump-column-defaults.mjs          # exit 1 if the file is stale
 *   node scripts/dump-column-defaults.mjs --write  # regenerate it
 */
import { PGlite } from '@electric-sql/pglite'
import { pgcrypto } from '@electric-sql/pglite/contrib/pgcrypto'
import { btree_gist } from '@electric-sql/pglite/contrib/btree_gist'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const MIGRATIONS = join(ROOT, 'supabase', 'migrations')
const OUT = join(ROOT, 'src', 'lib', '__mocks__', 'columnDefaults.ts')
const KIND = { 'now()': 'now', CURRENT_DATE: 'current_date' }

const db = await PGlite.create({ extensions: { pgcrypto, btree_gist } })
await db.exec(readFileSync(join(ROOT, 'supabase', 'pglite-prelude.sql'), 'utf8'))
for (const f of readdirSync(MIGRATIONS).filter((f) => f.endsWith('.sql')).sort()) {
  try {
    await db.exec(readFileSync(join(MIGRATIONS, f), 'utf8'))
  } catch (e) {
    console.error(`${f} failed to apply, so the schema is incomplete: ${String(e.message).split('\n')[0]}`)
    process.exit(2)
  }
}
const { rows } = await db.query(`
  select c.table_name, c.column_name, c.column_default
    from information_schema.columns c
    join information_schema.tables t
      on t.table_schema = c.table_schema and t.table_name = c.table_name
   where c.table_schema = 'public'
     and t.table_type = 'BASE TABLE'
     and c.column_default ~* '(now[(]|current_date|current_timestamp|clock_timestamp|localtimestamp)'
   order by c.table_name, c.column_name`)
await db.close()

const byTable = new Map()
for (const r of rows) {
  const kind = KIND[r.column_default]
  if (!kind) {
    console.error(`not mapped: ${r.table_name}.${r.column_name} default ${r.column_default}`)
    continue
  }
  if (!byTable.has(r.table_name)) byTable.set(r.table_name, [])
  byTable.get(r.table_name).push(`${r.column_name}: '${kind}'`)
}

const body = [...byTable].map(([table, cols]) => `  ${table}: { ${cols.join(', ')} },`).join('\n')
const file = `/**
 * GENERATED by \`node scripts/dump-column-defaults.mjs --write\`. Do not edit by hand.
 *
 * Every \`public\` base-table column whose default is \`now()\` or \`CURRENT_DATE\`,
 * after the whole migration chain. Postgres fills these when an INSERT leaves
 * them out; \`client.ts\` fills them the same way, so a row written in mock mode
 * carries what the live row would. Rerun the script after a migration adds or
 * drops such a default; without \`--write\` it exits 1 when this file is stale.
 */
export type TimeDefault = 'now' | 'current_date'

export const TIME_DEFAULTS: Readonly<Record<string, Readonly<Record<string, TimeDefault>>>> = {
${body}
}
`

let current = ''
try {
  current = readFileSync(OUT, 'utf8')
} catch {
  /* first run */
}
const columns = rows.filter((r) => KIND[r.column_default]).length
if (process.argv.includes('--write')) {
  writeFileSync(OUT, file)
  console.log(`wrote ${columns} columns across ${byTable.size} tables to src/lib/__mocks__/columnDefaults.ts`)
} else if (current.replace(/\r\n/g, '\n') !== file) {
  console.error('src/lib/__mocks__/columnDefaults.ts is stale. Run: node scripts/dump-column-defaults.mjs --write')
  process.exit(1)
} else {
  console.log(`columnDefaults.ts matches the schema: ${columns} columns across ${byTable.size} tables`)
}
